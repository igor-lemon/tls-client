package tls_client

import (
	tls "github.com/igor-lemon/utls"
	"github.com/igor-lemon/utls/behavior"
	"math/rand"
	"slices"
)

// chromeQUICSpec retains the profile's fresh key generation, trust anchors,
// certificate compression and ECH GREASE policy, adapting only TCP-specific
// fields to the TLS 1.3-only QUIC handshake measured in Chrome.
func chromeQUICSpec(id tls.ClientHelloID) func([]byte) (tls.ClientHelloSpec, error) {
	return profileQUICSpec(id, behavior.Legacy())
}
func profileQUICSpec(id tls.ClientHelloID, pol behavior.Policy) func([]byte) (tls.ClientHelloSpec, error) {
	return func(params []byte) (tls.ClientHelloSpec, error) {
		var spec tls.ClientHelloSpec
		var err error
		if id.SpecFactory != nil {
			spec, err = id.ToSpec()
		} else {
			spec, err = tls.UTLSIdToSpec(id)
		}
		if err != nil {
			return spec, err
		}
		spec.TLSVersMin = tls.VersionTLS13
		spec.TLSVersMax = tls.VersionTLS13
		spec.CipherSuites = nil
		for _, n := range pol.Numbers("quic.tls_cipher_suites") {
			spec.CipherSuites = append(spec.CipherSuites, uint16(n))
		}
		spec.CompressionMethods = []uint8{0}
		exts := make([]tls.TLSExtension, 0, len(spec.Extensions))
		var psk tls.PreSharedKeyExtension
		for _, ext := range spec.Extensions {
			if u, ok := ext.(interface{ Unwrap() tls.TLSExtension }); ok {
				// an extension a profile wraps for a TCP hello (tls-forge's
				// ALPS bound to its ALPN) goes as itself
				ext = u.Unwrap()
			}
			if !slices.Contains(pol.Numbers("quic.preserve_extensions"), quicExtensionID(ext)) {
				continue
			}
			switch e := ext.(type) {
			case *tls.SNIExtension, *tls.GREASEEncryptedClientHelloExtension, *tls.UtlsCompressCertExtension, *tls.PSKKeyExchangeModesExtension:
			case *tls.GenericExtension:
				if !slices.Contains(pol.Numbers("quic.preserve_extensions"), uint64(e.Id)) {
					continue
				}
			case *tls.SupportedCurvesExtension:
				curves := e.Curves[:0]
				for _, v := range e.Curves {
					if v != tls.GREASE_PLACEHOLDER || !pol.Flag("quic.remove_grease_groups") {
						curves = append(curves, v)
					}
				}
				e.Curves = curves
			case *tls.SignatureAlgorithmsExtension:
				// Chrome's QUIC TLS stack advertises this separately measured vector,
				// not the TCP stack's signature GREASE and post-quantum additions.
				e.SupportedSignatureAlgorithms = nil
				for _, n := range pol.Numbers("quic.tls_signature_algorithms") {
					e.SupportedSignatureAlgorithms = append(e.SupportedSignatureAlgorithms, tls.SignatureScheme(n))
				}
			case *tls.KeyShareExtension:
				shares := e.KeyShares[:0]
				for _, v := range e.KeyShares {
					if v.Group != tls.GREASE_PLACEHOLDER || !pol.Flag("quic.remove_grease_groups") {
						shares = append(shares, v)
					}
				}
				e.KeyShares = shares
			case *tls.ALPNExtension:
				e.AlpnProtocols = pol.Strings("quic.alpn")
			case *tls.ApplicationSettingsExtension:
				// ALPS for the protocols of quic.alps_protocols, with no settings
				// of the client's own (as Chrome's QUIC hello), which the HTTP/3
				// transport reads the server's of (h3.alps_reader)
				e.SupportedProtocols = pol.Strings("quic.alps_protocols")
			case *tls.ApplicationSettingsExtensionNew:
				e.SupportedProtocols = pol.Strings("quic.alps_protocols")
			case *tls.SupportedVersionsExtension:
				e.Versions = nil
				for _, n := range pol.Numbers("quic.tls_versions") {
					e.Versions = append(e.Versions, uint16(n))
				}
			case tls.PreSharedKeyExtension:
				psk = e
				continue
			default:
				continue
			}
			exts = append(exts, ext)
		}
		// QUIC parameters are generated by the live transport, not imported from a
		// TCP profile or a different connection's capture.
		exts = append(exts, &tls.GenericExtension{Id: 57, Data: append([]byte(nil), params...)})
		if pol.Flag("quic.shuffle_extensions") {
			rand.Shuffle(len(exts), func(i, j int) { exts[i], exts[j] = exts[j], exts[i] })
		}
		if psk != nil {
			exts = append(exts, psk)
		}
		spec.Extensions = exts
		return spec, nil
	}
}

func quicExtensionID(ext tls.TLSExtension) uint64 {
	switch e := ext.(type) {
	case *tls.SNIExtension:
		return 0
	case *tls.GREASEEncryptedClientHelloExtension:
		return 65037
	case *tls.UtlsCompressCertExtension:
		return 27
	case *tls.PSKKeyExchangeModesExtension:
		return 45
	case *tls.GenericExtension:
		return uint64(e.Id)
	case *tls.SupportedCurvesExtension:
		return 10
	case *tls.SignatureAlgorithmsExtension:
		return 13
	case *tls.KeyShareExtension:
		return 51
	case *tls.ALPNExtension:
		return 16
	case *tls.SupportedVersionsExtension:
		return 43
	case tls.PreSharedKeyExtension:
		return 41
	case *tls.ApplicationSettingsExtension:
		return 17513
	case *tls.ApplicationSettingsExtensionNew:
		return 17613
	}
	return ^uint64(0)
}
